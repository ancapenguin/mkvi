void main() {
  group('the official fixture is what the format says it is', () {
    test('the .sig file has the four lines the format requires', () {
      final String text = signatureBlock(officialSignatureB64)!;
      final List<String> lines = rustLines(text);

      expect(lines, hasLength(4));
      expect(lines[0], startsWith('untrusted comment: '));
      expect(lines[2], startsWith('trusted comment: '));
      // minisign-verify 0.3.0 rejects a block whose third line is not prefixed
      // `trusted comment: ` (`Signature::decode`), so this is load bearing
      // rather than cosmetic.
      expect(decodeStandard(lines[1].trim()), hasLength(74));
      expect(decodeStandard(lines[3].trim()), hasLength(64));
      // The official writer terminates the file. That trailing newline is part
      // of the bytes, which is why what goes into `latest.json` is base64 of the
      // whole file rather than of the payload alone.
      expect(text.endsWith('\n'), isTrue);
    });

    test('the signature is tagged ED, the only form MKVI accepts', () {
      final String text = signatureBlock(officialSignatureB64)!;
      expect(algorithmOf(text), prehashedTag);
    });

    test('the public key is 42 bytes and is tagged Ed, as the format says', () {
      final String text = keyBlock(officialPubFileB64)!;
      final List<String> lines = rustLines(text);
      expect(lines, hasLength(2));
      expect(lines[0], startsWith('untrusted comment: minisign public key: '));
      expect(algorithmOf(text), keyTag);
      expect(decodeStandard(lines[1].trim()), hasLength(42));
      // The bare form is the same 42 bytes, so the two shapes
      // `UpdateConfig.publicKeyB64` accepts really do name one key.
      expect(decodeStandard(lines[1].trim()), decodeStandard(officialPubBareB64));
    });

    test('the key id in the signature is the key id in the key', () {
      final List<int> signed = decodeStandard(
        rustLines(signatureBlock(officialSignatureB64)!)[1].trim(),
      )!;
      final List<int> key = decodeStandard(officialPubBareB64)!;
      // Bytes 2..10 of both blocks. minisign-verify refuses a mismatch with
      // `UnexpectedKeyId` before it hashes anything, so a fixture with the wrong
      // key id would be a fixture that can never verify.
      expect(signed.sublist(2, 10), key.sublist(2, 10));
    });

    test('the payload the fixture signs is the one that was signed', () {
      expect(decodeStandard(officialPayloadB64), hasLength(590));
    });
  });

  group("MKVI's reader rules, applied to the official bytes", () {
    test('the signature is readable and is the accepted algorithm', () {
      final String text = signatureBlock(officialSignatureB64)!;
      expect(algorithmOf(text), isNotNull);
      expect(_same(algorithmOf(text)!, prehashedTag), isTrue);
    });

    test('both accepted key shapes decode, through different branches', () {
      // Different branches on purpose. The bare form never reaches `key_block`
      // - 42 random bytes are not UTF-8 - so a reader that only implemented the
      // `.pub` file shape would pass a test written with a `.pub` fixture and
      // fail on the value a build is most likely to be given.
      expect(decodePublicKeyShape(officialPubBareB64), 'bare 42 bytes');
      expect(decodePublicKeyShape(officialPubFileB64), 'whole .key.pub file');
      expect(keyBlock(officialPubBareB64), isNull);
      expect(keyIsLegacy('base64 degil'), isNull);
    });

    test('canonical base64 padding is load bearing, not decoration', () {
      // This is what a well-meaning "clean up the build flag" edit produces, and
      // the Rust core rejects it: `general_purpose::STANDARD` requires the `=`.
      final String unpaddedSignature = officialSignatureB64.replaceAll('=', '');
      expect(officialSignatureB64.endsWith('=='), isTrue);
      expect(decodeStandard(unpaddedSignature), isNull);
      // And the value has to be the whole file, not a trimmed payload: drop the
      // comment lines and the algorithm tag is no longer on line 1.
      final List<String> payloadOnly = rustLines(signatureBlock(officialSignatureB64)!)
          .where((String line) => !line.startsWith('untrusted comment: '))
          .toList();
      expect(algorithmOf(payloadOnly.join('\n')), isNull);
    });

    // -----------------------------------------------------------------------
    // RECORDED MEASUREMENT - NOT AN ENDORSEMENT.
    //
    // Everything below this line documents a defect. It is written as a test so
    // that it cannot be quietly forgotten, and so that whoever fixes it cannot
    // fix it without this file going red and being updated on purpose.
    //
    // The measured facts, 2026-09-26, against official `minisign` crate 0.10.0:
    //
    //   * minisign's published format specification lists
    //     `signature_algorithm: Ed` for the **public key** and offers `ED` for
    //     the **signature**. The official implementation follows its own
    //     specification: both of its key generation paths,
    //     `generate_unencrypted_keypair()` and `generate_encrypted_keypair()`,
    //     write a key tagged `Ed`. Measured on both, above.
    //   * `minisign-verify` 0.3.0 - the crate MKVI actually verifies with -
    //     accepts **both** tags on a key (`PublicKey::from_base64`:
    //     `(0x45,0x64) | (0x45,0x44) => {}`). `allow_legacy` gates the
    //     *signature* algorithm only; it never inspects the key's tag.
    //   * So the key's tag carries no security meaning, and `key_is_legacy`
    //     reading it as "retired" is MKVI's own rule, not the format's.
    //     `verify_artifact` (update.rs:103) short-circuits on it, so **as
    //     written 0.2.0 refuses every key the official tool can produce.**
    //
    // The fix is not in this file and not in `app/`. It is
    // `crates/mkvi_core/src/update.rs:129` and `:103`, plus three Dart doc
    // comments that repeat the same misdiagnosis
    // (`app/lib/update/update_config.dart:158`, `update_preflight.dart:11`,
    // `update_verifier.dart`). One of them advises minting the key with
    // `minisign -W`, which cannot help: `-W` means "do not encrypt the secret
    // key", and the key it writes is tagged `Ed` either way.
    //
    // When that is fixed these two assertions are inverted and the block above
    // them is deleted. Do not delete the block first.
    // -----------------------------------------------------------------------
    test('RECORDED: the official key is called legacy by update.rs:129', () {
      expect(keyIsLegacy(officialPubBareB64), isTrue);
      expect(keyIsLegacy(officialPubFileB64), isTrue);
    });

    test('RECORDED: the tag is the only thing standing between the two', () {
      // `verify_artifact` returns `UpdateError::LegacyKey` before it ever looks
      // at the signature, so no official signature can be accepted under an
      // official key however it was produced. The measured exception: changing
      // the key's second tag byte from `d` to `D` by hand - an edit no tool
      // performs - is enough for the same official signature to be ACCEPTED.
      // That is the whole gap, and it is one byte wide.
      final List<int> raw = decodeStandard(officialPubBareB64)!;
      expect(_same(raw.sublist(0, 2), keyTag), isTrue);
      raw[1] = 0x44; // "Ed" -> "ED"
      expect(_same(raw.sublist(0, 2), prehashedTag), isTrue);
      expect(keyIsLegacy(base64.encode(raw)), isFalse);
    });
  });

  group('the value survives the Dart layer byte for byte', () {
    // The Dart layer is not allowed to interpret a signature - it carries it.
    // What it *is* responsible for is not mangling it on the way past, and the
    // official fixture is what makes that checkable: a stripped `=`, a trimmed
    // newline or a re-wrapped comment would all still be "a base64 string" to
    // any test written with a made-up fixture, and all three break the core.
    test('the feed hands the signature on unchanged', () {
      final Map<String, Object?> feed = <String, Object?>{
        'version': '0.2.1',
        'notes': 'Düzeltmeler',
        'platforms': <String, Object?>{
          windowsUpdateTarget: <String, Object?>{
            'url':
                'https://github.com/ancapenguin/mkvi/releases/download/v0.2.1/mkvi-setup.exe',
            'signature': officialSignatureB64,
          },
        },
      };
      final UpdateManifest parsed = parseUpdateManifest(
        utf8.encode(jsonEncode(feed)),
        ReleaseVersion.tryParse('0.2.0')!,
      );
      expect(parsed, isA<ManifestOffersRelease>());
      final UpdateOffer offer = (parsed as ManifestOffersRelease).offer;
      expect(offer.signature, officialSignatureB64);
    });

    test('the config keeps the key unchanged', () {
      final UpdateConfig config = UpdateConfig(
        currentVersion: '0.2.0',
        feedUrl: Uri.parse(
          'https://github.com/ancapenguin/mkvi/releases/latest/download/latest.json',
        ),
        publicKeyB64: officialPubFileB64,
      );
      expect(config.publicKeyB64, officialPubFileB64);
      // `hasReleaseKey` is a `trim().isNotEmpty`, so it must not be asked to
      // judge the shape. A key that reads as legacy is still a key that arrived,
      // and the preflight's next question is the one that is supposed to decide.
      expect(config.hasReleaseKey, isTrue);
      expect(config.isConfigured, isTrue);
    });
  });
}
