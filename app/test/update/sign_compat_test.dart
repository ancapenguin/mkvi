/// The prehashed algorithm tag, `ED`. The only signature form
/// `verify_artifact` accepts (`update.rs:151`).
const List<int> prehashedTag = <int>[0x45, 0x44];

/// The tag the **key** carries: `Ed`, not `ED` - and that is not a mistake in
/// the fixture. The published minisign format specifies `Ed` for the public key
/// and offers `ED` for the signature; `docs/signing.md` has the measurement and
/// the upstream wording.
const List<int> keyTag = <int>[0x45, 0x64];

// ---------------------------------------------------------------------------
// MKVI's reader rules, transcribed from crates/mkvi_core/src/update.rs.
//
// A TRANSCRIPTION, NOT THE RULE ITSELF. These are Dart copies of `algorithm_of`
// (update.rs:157), `signature_block` (:167), `key_block` (:176),
// `decode_public_key` (:190) and `key_is_legacy` (:129), so a Dart test can say
// what those rules do to the official bytes. They cannot stand in for the Rust
// code - the Ed25519 check is not here and is not reachable from here - so every
// test below is asserting about a rule, never about a signature being valid.
// ---------------------------------------------------------------------------

/// `str::lines()`: split on `\n`, then drop the single empty piece a trailing
/// newline leaves behind. The official writer terminates both files, so a plain
/// `split` would report five lines for a four line signature.
List<String> rustLines(String text) {
  final List<String> parts = text.split('\n');
  if (parts.isNotEmpty && parts.last.isEmpty) parts.removeLast();
  return parts;
}

/// `base64::engine::general_purpose::STANDARD`, which in Rust 0.22 requires
/// canonical padding. Whitespace and a missing `=` are both errors there, and
/// both are errors here.
List<int>? decodeStandard(String value) {
  if (value.length % 4 != 0) return null;
  try {
    return base64.decode(value);
  } on FormatException {
    return null;
  }
}

/// `algorithm_of`, update.rs:157. Line 1 is the payload and its first two bytes
/// are the tag.
List<int>? algorithmOf(String block) {
  final List<String> lines = rustLines(block);
  if (lines.length < 2) return null;
  final List<int>? decoded = decodeStandard(lines[1].trim());
  if (decoded == null || decoded.length < 2) return null;
  return decoded.sublist(0, 2);
}

/// `signature_block`, update.rs:167: base64 of a whole `.sig` file, read as
/// UTF-8 text.
String? signatureBlock(String signatureB64) {
  final List<int>? raw = decodeStandard(signatureB64.trim());
  if (raw == null) return null;
  try {
    return utf8.decode(raw);
  } on FormatException {
    return null;
  }
}

/// `key_block`, update.rs:176: either the file text itself, or base64 of it.
///
/// Note what this does **not** do: it cannot read the bare 42 byte form, because
/// 42 random bytes are not UTF-8. That is why `decode_public_key` tries the bare
/// form first, and the order is load bearing - see [decodePublicKeyShape].
String? keyBlock(String publicKeyB64) {
  final String trimmed = publicKeyB64.trim();
  if (trimmed.contains('untrusted comment:')) return trimmed;
  final List<int>? raw = decodeStandard(trimmed);
  if (raw == null) return null;
  try {
    return utf8.decode(raw);
  } on FormatException {
    return null;
  }
}

/// Which of the two shapes `decode_public_key` (update.rs:190) ends up taking,
/// or `null` for `UpdateError::MalformedKey`.
///
/// The order is the opposite of `key_is_legacy`'s, and the two functions
/// therefore disagree about a bare key: this one accepts it, the other calls it
/// legacy. Both orderings are faithful to the Rust.
String? decodePublicKeyShape(String publicKeyB64) {
  final String trimmed = publicKeyB64.trim();
  // `PublicKey::from_base64(trimmed)` is tried first, update.rs:192.
  final List<int>? bare = decodeStandard(trimmed);
  if (bare != null && bare.length == 42) return 'bare 42 bytes';
  // Only then `PublicKey::decode(&key_block(trimmed)?)`, update.rs:195.
  final String? block = keyBlock(trimmed);
  if (block == null) return null;
  final List<String> lines = rustLines(block);
  if (lines.length < 2) return null;
  final List<int>? decoded = decodeStandard(lines[1].trim());
  if (decoded == null || decoded.length != 42) return null;
  return 'whole .key.pub file';
}

/// `key_is_legacy`, update.rs:129. `null` stands for `UpdateError::MalformedKey`.
bool? keyIsLegacy(String publicKeyB64) {
  final String trimmed = publicKeyB64.trim();
  final List<int>? raw = decodeStandard(trimmed);
  if (raw != null) {
    try {
      final List<int>? tag = algorithmOf(utf8.decode(raw));
      if (tag != null) return _same(tag, keyTag);
    } on FormatException {
      // Not text: fall through to the bare-key reading, exactly as Rust does.
    }
    if (raw.length >= 2) return _same(raw.sublist(0, 2), keyTag);
  }
  final List<int>? direct = algorithmOf(trimmed);
  if (direct != null) return _same(direct, keyTag);
  return null;
}

bool _same(List<int> a, List<int> b) {
  if (a.length != b.length) return false;
  for (int i = 0; i < a.length; i++) {
    if (a[i] != b[i]) return false;
  }
  return true;
}

