/// Sign compatibility: does MKVI speak the same minisign dialect that the
/// official tool speaks?
///
/// ## What this file is for
///
/// The release key is produced by `minisign`, not by MKVI, so the only question
/// that matters before 0.2.0 can ship is whether the two agree. This file pins
/// that agreement against **one fixture produced by the official
/// implementation itself**, so a change in either dialect shows up as a failing
/// test rather than as a failed update on a user's machine.
///
/// ## The fixture is real, and here is exactly where it came from
///
/// Produced on 2026-09-26 by a throwaway crate outside this repository that
/// depended on **both** the `minisign` crate (v0.10.0, jedisct1's own Rust
/// implementation) and `mkvi_core` as a path dependency. The recipe is written
/// out in `docs/signing.md` so the fixture can be regenerated. The key pair was
/// created in memory, used once, and dropped: it was never written to disk and
/// it is not a release key. Only the **public** half and one signature over a
/// fixed public payload are recorded here, which is all a compatibility fixture
/// can safely contain.
///
/// The Windows `minisign` **CLI** is not installed on this machine and was
/// deliberately not installed; `docs/signing.md` records what `scoop` and
/// `winget` offer. The crate is the implementation the CLI is built on
/// (`rsign2` is described upstream as "a command-line tool reimplementing the
/// Minisign utility in Rust, and based on this crate"), so it is the right thing
/// to measure against - but that substitution is a judgement, not a proof, and
/// it is called out in the document rather than buried here.
///
/// ## What this file CANNOT prove, and why that is not fixable in Dart
///
/// It cannot check a single Ed25519 signature, and it does not pretend to:
///
/// * `app/pubspec.yaml` has **no cryptography dependency at all** - no
///   `ed25519`, no `cryptography`, nothing. Adding one to make a test able to
///   verify a signature would be adding a second implementation of the thing
///   `mkvi_core` exists to own, which `app/lib/update/update_verifier.dart`
///   explicitly forbids.
/// * The app **cannot call `mkvi_core`**. `flutter_rust_bridge` is not a
///   dependency of this package, `mkvi_core` exposes no C ABI, and the only
///   `SignatureVerifier` in `lib/` is `UnavailableSignatureVerifier`, which
///   refuses everything by design. So there is no Dart-reachable path to
///   `verify_artifact`.
///
/// The cryptographic verdict - "does an official signature pass MKVI's
/// verifier, and is a flipped byte rejected" - was therefore **measured by
/// running both implementations against each other**, and the result is
/// recorded in `docs/signing.md`. The short version, because it is the whole
/// point of this file existing: the *signature* is byte-for-byte compatible in
/// both directions, and the *key* is not, because MKVI's key classifier reads
/// the spec-mandated `Ed` key tag as "legacy".
